// Machine-drafted and NOT reviewed by a native speaker. Terminology follows
// what Finnish speakers see in Office and Google Slides (dia, esitys,
// asettelu, objekti, siirtymä, täyttö, viiva). One rendering per concept,
// never varied.
//
// Two Finnish-specific rules held throughout:
//   * Finnish inflects with ~15 cases, and vowel harmony (a/ä, o/ö, u/y)
//     decides which form a suffix takes. A case ending glued to an
//     interpolated {placeholder} would therefore be wrong for a large share
//     of the values it ever sees, since the value's own vowels are unknown
//     here. Those strings are rephrased so the ending rides on a FIXED word
//     — the value goes after a colon, or into a construction that needs no
//     ending on the value at all.
//   * No plural machinery exists in t(). Finnish wants the partitive
//     singular after a numeral ("3 diaa") but the nominative at n=1
//     ("1 dia"), so counted strings use a colon or another count-agnostic
//     form rather than picking one and being wrong half the time.
