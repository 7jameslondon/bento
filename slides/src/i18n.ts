// Facade: the i18n ENGINE lives in the shared kernel (kernel/src/i18n.ts);
// the CATALOGS are this app's string data and stay here in ./i18n/*.ts.
//
// This module registers them at import time and re-exports the engine, so
// every consumer keeps importing './i18n' unchanged AND catalog registration
// is guaranteed to precede the first t() call by ES module evaluation order.
// App code must never import the kernel i18n directly — that would bypass
// this registration.

// The per-locale catalogs in ./i18n/*.ts are the SOURCE OF TRUTH (that is what
// a translator reviews and a contributor submits). What SHIPS is the key-once
// packing of them, generated by scripts/build-i18n.mjs — importing the
// per-locale files here instead would put every English key in the bundle
// seven times over. Regenerate after editing any catalog:
//
//     node scripts/build-i18n.mjs
//
import { PACKED, PACKED_LOCALES } from './i18n/packed'
import { readPacksFromShell, refreshPacksForVersion, shellBlocksForPacks } from './packs'
import { registerShellBlocks } from '../../kernel/src/save.ts'
import { registerUpdatePrepare } from '../../kernel/src/update.ts'
import { registerI18n } from '../../kernel/src/i18n.ts'
import type { LocaleChoice } from '../../kernel/src/i18n.ts'

export type { Catalog } from '../../kernel/src/i18n.ts'

/** Locales offered in the About picker (label in its own language). */
const CHOICES: LocaleChoice[] = [
  { code: 'en', label: 'English' },
  { code: 'ja', label: '日本語' },
  { code: 'zh-Hans', label: '简体中文' },
  { code: 'zh-Hant', label: '繁體中文' },
  { code: 'es', label: 'Español' },
  { code: 'fr', label: 'Français' },
  { code: 'it', label: 'Italiano' },
  { code: 'de', label: 'Deutsch' },
  { code: 'pt', label: 'Português' },
]

registerI18n({
  packed: {
    locales: PACKED_LOCALES,
    table: PACKED,
    alias: {
      zh: 'zh-Hans', // zh, zh-CN, zh-SG → simplified
      'zh-CN': 'zh-Hans',
      'zh-SG': 'zh-Hans',
      'zh-TW': 'zh-Hant',
      'zh-HK': 'zh-Hant',
      // Brazilian terminology; pt-PT differs enough to deserve its own
      // catalog later (docs/i18n-packs.md) — until then it maps here.
      'pt-BR': 'pt',
      'pt-PT': 'pt',
    },
  },
  choices: CHOICES,
})

// Packs embedded in this file, registered before the first t() — the same
// module-evaluation-order guarantee that makes the facade own registration.
// A pack lives in the FILE and nowhere else (see ./packs.ts for why).
readPacksFromShell()

// Every save re-declares the file's packs, so staging one is enough to make
// it travel and dropping it is enough to remove it.
registerShellBlocks(shellBlocksForPacks)

// A self-update fetches a NEW shell and re-splices this document into it. The
// block provider above already carries the file's packs across; this also
// brings them UP TO the new version, so a translated deck doesn't drift back
// toward English one release at a time. Best effort — see refreshPacksForVersion.
registerUpdatePrepare(async (version) => { await refreshPacksForVersion(version) })

/**
 * The BUNDLED locales only. Call sites that need the live list — including any
 * language an installed pack added — must use `localeChoices()` instead: this
 * const is frozen at import and can never grow.
 */
export const LOCALE_CHOICES = CHOICES

export { t, locale, setLocale, i18nApi, localeChoices } from '../../kernel/src/i18n.ts'
